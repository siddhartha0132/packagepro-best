// Voice evaluation: 20 trip requests (5 each in English, Hindi, Tamil, Telugu) → speech (Sarvam bulbul:v3) → the real
// pipeline (hear → English meaning → trip planner) → scored on destination, trip length and detected language.
// Writes docs/VOICE_EVAL.md. Needs SARVAM_API_KEY in .env. Usage: pnpm voice:eval
import "dotenv/config";
import { writeFileSync } from "node:fs";
import { explainWithFreeOpenRouter } from "../ai/pipeline";
import { DESTINATIONS, ORIGINS } from "../backend/src/integrations";
import { hear, speak, voiceEnabled } from "../backend/src/voice";

type Case = { language: "en-IN" | "hi" | "ta" | "te"; text: string; city: string; days: number };
const EXPECTED: [string, number][] = [["Thanjavur", 3], ["Panaji", 5], ["Manali", 7], ["Jaipur", 2], ["Udaipur", 4]];
const PHRASES: Record<Case["language"], string[]> = {
  "en-IN": ["Plan a three day trip to Thanjavur from Delhi", "I want to go to Goa for five days", "Plan a trip to Manali for a week", "Take me to Jaipur for two days from Mumbai", "Plan a four day holiday in Udaipur"],
  hi: ["दिल्ली से तंजावुर की तीन दिन की यात्रा प्लान करो", "मुझे पाँच दिन के लिए गोवा जाना है", "एक हफ्ते के लिए मनाली की ट्रिप प्लान करो", "मुंबई से जयपुर दो दिन के लिए ले चलो", "उदयपुर में चार दिन की छुट्टी प्लान करो"],
  ta: ["டெல்லியிலிருந்து தஞ்சாவூருக்கு மூன்று நாள் பயணம் திட்டமிடுங்கள்", "ஐந்து நாட்களுக்கு கோவா செல்ல வேண்டும்", "ஒரு வாரத்திற்கு மணாலி பயணம் திட்டமிடுங்கள்", "மும்பையிலிருந்து ஜெய்ப்பூருக்கு இரண்டு நாட்கள் பயணம்", "உதய்பூரில் நான்கு நாள் விடுமுறை திட்டமிடுங்கள்"],
  te: ["ఢిల్లీ నుండి తంజావూరుకు మూడు రోజుల ప్రయాణం ప్లాన్ చేయండి", "ఐదు రోజుల కోసం గోవా వెళ్లాలి", "ఒక వారం మనాలి ట్రిప్ ప్లాన్ చేయండి", "ముంబై నుండి జైపూర్‌కు రెండు రోజుల ప్రయాణం", "ఉదయ్‌పూర్‌లో నాలుగు రోజుల సెలవు ప్లాన్ చేయండి"],
};
const CASES: Case[] = (Object.keys(PHRASES) as Case["language"][]).flatMap(language => PHRASES[language].map((text, index) => ({ language, text, city: EXPECTED[index][0], days: EXPECTED[index][1] })));
const LABEL: Record<Case["language"], string> = { "en-IN": "English", hi: "Hindi", ta: "Tamil", te: "Telugu" };

if (!voiceEnabled()) {
  console.error("SARVAM_API_KEY is not set — the voice evaluation needs the real speech service.");
  process.exit(1);
}

type Row = Case & { heardNative: string; heardEnglish: string; detected: string; gotCity?: string; gotDays?: number; ms: number; ok: { city: boolean; days: boolean; language: boolean } };
const rows: Row[] = [];
for (const item of CASES) {
  const audio = await speak(item.text, item.language);
  if (!audio) { console.error("speech failed for", item.text); continue; }
  const started = Date.now();
  const heard = await hear(audio, "audio/mpeg");
  const result = heard ? await explainWithFreeOpenRouter([{ role: "user", content: heard.english }], { language: item.language, availableOrigins: ORIGINS, availableDestinations: DESTINATIONS }) as { tripRequest?: { destination?: { city: string }; durationDays?: number } } : undefined;
  const ms = Date.now() - started;
  const gotCity = result?.tripRequest?.destination?.city;
  const gotDays = result?.tripRequest?.durationDays;
  const row: Row = { ...item, heardNative: heard?.native ?? "", heardEnglish: heard?.english ?? "", detected: heard?.language ?? "", gotCity, gotDays, ms, ok: { city: gotCity === item.city, days: gotDays === item.days, language: heard?.language === item.language } };
  rows.push(row);
  console.log(`${row.ok.city && row.ok.days ? "✓" : "✗"} ${LABEL[item.language].padEnd(7)} ${item.city.padEnd(9)} ${String(item.days).padStart(2)}d → ${(gotCity ?? "—").padEnd(9)} ${String(gotDays ?? "—").padStart(2)}d · lang ${row.detected || "—"} · ${ms} ms · "${row.heardEnglish}"`);
}

const pct = (count: number, total: number) => `${Math.round((count / Math.max(1, total)) * 100)}%`;
const total = rows.length;
const both = rows.filter(row => row.ok.city && row.ok.days).length;
const byLanguage = (Object.keys(LABEL) as Case["language"][]).map(language => {
  const subset = rows.filter(row => row.language === language);
  return `| ${LABEL[language]} | ${subset.filter(row => row.ok.city && row.ok.days).length}/${subset.length} | ${subset.filter(row => row.ok.city).length}/${subset.length} | ${subset.filter(row => row.ok.days).length}/${subset.length} | ${subset.filter(row => row.ok.language).length}/${subset.length} | ${Math.round(subset.reduce((sum, row) => sum + row.ms, 0) / Math.max(1, subset.length))} ms |`;
});
const invented = rows.filter(row => row.gotCity && !DESTINATIONS.some(place => place.city === row.gotCity)).length;
const median = [...rows.map(row => row.ms)].sort((a, b) => a - b)[Math.floor(total / 2)] ?? 0;

const report = `# Voice evaluation

Generated by \`pnpm voice:eval\` on ${new Date().toISOString().slice(0, 10)}. Each request is spoken with Sarvam \`bulbul:v3\`, then sent through the
real pipeline: \`hear()\` (Sarvam \`saarika:v2.5\` words as spoken + \`saaras:v2.5\` English meaning) → the trip planner
(rules first, Sarvam \`sarvam-105b\` fallback) → scored against the expected destination and length.

**Overall: ${both}/${total} correct (${pct(both, total)})** · destination ${pct(rows.filter(r => r.ok.city).length, total)} · length ${pct(rows.filter(r => r.ok.days).length, total)} · language detected ${pct(rows.filter(r => r.ok.language).length, total)} · **invented destinations: ${invented}** · median time from audio to plan: **${median} ms**

| Language | Correct (place + days) | Destination | Trip length | Language detected | Avg. time |
|---|---|---|---|---|---|
${byLanguage.join("\n")}

## Every request

| Language | Said | Heard (English meaning) | Expected | Got | Time |
|---|---|---|---|---|---|
${rows.map(row => `| ${LABEL[row.language]} | ${row.text} | ${row.heardEnglish} | ${row.city} · ${row.days}d | ${row.gotCity ?? "—"} · ${row.gotDays ?? "—"}d ${row.ok.city && row.ok.days ? "✓" : "✗"} | ${row.ms} ms |`).join("\n")}

**Honest limits:** the clips are synthetic (clear studio speech); real phone recordings with background noise will score lower.
The next step is 50+ real voice notes from different speakers.
`;
writeFileSync("docs/VOICE_EVAL.md", report);
console.log(`\n${both}/${total} correct (${pct(both, total)}) · invented destinations: ${invented} · median ${median} ms → docs/VOICE_EVAL.md`);
